function match(input: Omit<Match, "lockAt" | "status"> & Partial<Pick<Match, "status">>): Match {
  return {
    ...input,
    lockAt: getLockAt(input.kickoffAt),
    status: input.status ?? "SCHEDULED",
  };
}

